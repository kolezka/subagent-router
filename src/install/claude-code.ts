// Plans the Claude Code integration artifacts `subagent-router install` writes. Pure: it returns
// file contents and never touches the filesystem, so the CLI owns every write and every guard.
//
// The integration point is ANTHROPIC_BASE_URL, not a provider name. Claude Code talks to the
// router, the router talks to whatever gateway ROUTER_GATEWAY_URL names, so nothing generated here
// mentions a provider, a model vendor or a credential.
import { posixQuote } from '../agents/export';

export interface InstallFile {
  relativePath: string;
  content: string;
  /** Shell scripts Claude Code or the operator spawns directly need the executable bit. */
  executable?: boolean;
}

export interface ClaudeCodeInstallPlan {
  routerUrl: string;
  files: InstallFile[];
}

export interface ClaudeCodeInstallOptions {
  /** Where `serve` listens, already normalized for a client to dial. */
  routerUrl: string;
  /** Absolute path to the operator config `serve` is started with. */
  configPath: string;
  /** Absolute path to the packaged CLI, used in the generated commands. */
  cliPath: string;
  /** Package version, recorded in plugin.json. */
  version: string;
  /** Optional parent model, exported as ANTHROPIC_MODEL when the gateway needs an explicit one. */
  parentModel?: string;
  /** Optional client version for the generated `serve` command line. */
  claudeVersion?: string;
}

// Claude Code sends its own Authorization header, and the router only replaces the headers named
// in ROUTER_GATEWAY_HEADERS. Without this placeholder a logged-in client would forward its real
// Anthropic credential to a third-party gateway. The value is deliberately not a credential.
export const PLACEHOLDER_AUTH_TOKEN = 'subagent-router-placeholder-not-a-credential';

/** The router's local control endpoint. It answers in the serving process and never forwards. */
export const HEALTH_PATH = '/subagent-router/control/instance';

/**
 * Turns a `serve` host into a host a client can dial. A wildcard bind address is a listen-side
 * concept; a client that connects to 0.0.0.0 or :: reaches nothing on most platforms.
 */
export function clientHost(host: string): string {
  if (host === '0.0.0.0') return '127.0.0.1';
  if (host === '::' || host === '[::]') return '[::1]';
  return host.includes(':') && !host.startsWith('[') ? `[${host}]` : host;
}

export function routerUrlFor(host: string, port: number): string {
  return `http://${clientHost(host)}:${port}`;
}

function settingsFile(options: ClaudeCodeInstallOptions): InstallFile {
  const env: Record<string, string> = {
    ANTHROPIC_BASE_URL: options.routerUrl,
    ANTHROPIC_AUTH_TOKEN: PLACEHOLDER_AUTH_TOKEN,
  };
  if (options.parentModel !== undefined) env.ANTHROPIC_MODEL = options.parentModel;

  const settings = {
    _note: 'Generated by `subagent-router install`. Pass it to Claude Code with --settings; it is not merged into your own settings.json.',
    env,
  };
  return { relativePath: 'settings.json', content: `${JSON.stringify(settings, null, 2)}\n` };
}

function launcherFile(options: ClaudeCodeInstallOptions, settingsPath: string): InstallFile {
  const serveCommand = [
    posixQuote(options.cliPath),
    'serve',
    '--config',
    posixQuote(options.configPath),
    ...(options.claudeVersion !== undefined ? ['--claude-version', posixQuote(options.claudeVersion)] : []),
  ].join(' ');

  const content = `#!/bin/sh
# Generated by \`subagent-router install\`. Regenerate it instead of editing it.
# Starts your own Claude Code against the router without changing your installed configuration.
set -eu

ROUTER_URL=${posixQuote(options.routerUrl)}
SETTINGS=${posixQuote(settingsPath)}

if command -v curl >/dev/null 2>&1; then
  if ! curl -sf -o /dev/null --max-time 2 "$ROUTER_URL${HEALTH_PATH}"; then
    echo "subagent-router: no router answers at $ROUTER_URL" >&2
    echo "start it first: ${serveCommand}" >&2
    exit 2
  fi
fi

exec claude --settings "$SETTINGS" "$@"
`;
  return { relativePath: 'claude-router', content, executable: true };
}

function pluginManifest(options: ClaudeCodeInstallOptions): InstallFile {
  // Only identity and metadata. A plugin manifest cannot set environment variables, so the routing
  // itself stays in settings.json; the plugin adds the session check and the status command.
  const manifest = {
    name: 'subagent-router',
    version: options.version,
    description: 'Explicit upstream model routing for native Claude Code subagents.',
  };
  return { relativePath: '.claude-plugin/plugin.json', content: `${JSON.stringify(manifest, null, 2)}\n` };
}

function hooksManifest(): InstallFile {
  const hooks = {
    hooks: {
      SessionStart: [{ hooks: [{ type: 'command', command: '"${CLAUDE_PLUGIN_ROOT}"/hooks/check-router.sh' }] }],
    },
  };
  return { relativePath: 'hooks/hooks.json', content: `${JSON.stringify(hooks, null, 2)}\n` };
}

function healthCheckScript(options: ClaudeCodeInstallOptions): InstallFile {
  // Silent when everything is in place. A session-start hook that prints on success would add a
  // line of noise to every session for no decision the reader has to make.
  const content = `#!/bin/sh
# Generated by \`subagent-router install\`. Reports routing problems at session start.
# It never blocks a session: it exits 0 whatever it finds.
ROUTER_URL=${posixQuote(options.routerUrl)}

if [ "\${ANTHROPIC_BASE_URL:-}" != "$ROUTER_URL" ]; then
  echo "subagent-router: ANTHROPIC_BASE_URL is not $ROUTER_URL, so subagent model routing is off in this session."
  exit 0
fi

if ! command -v curl >/dev/null 2>&1; then
  echo "subagent-router: curl is missing, so the router was not checked."
  exit 0
fi

if ! curl -sf -o /dev/null --max-time 2 "$ROUTER_URL${HEALTH_PATH}"; then
  echo "subagent-router: no router answers at $ROUTER_URL. Every request in this session will fail."
fi
exit 0
`;
  return { relativePath: 'hooks/check-router.sh', content, executable: true };
}

function statusCommand(options: ClaudeCodeInstallOptions): InstallFile {
  const check = `${posixQuote(options.cliPath)} config check --config ${posixQuote(options.configPath)} --json`;
  const models = `${posixQuote(options.cliPath)} models list --config ${posixQuote(options.configPath)} --json`;
  const content = `---
description: Report the subagent-router config, catalog and router health.
---

Run these two commands and report what they return. Change nothing.

\`\`\`sh
${check}
${models}
\`\`\`

Then report, in this order:

1. Whether \`config check\` exited 0. If not, quote each problem code exactly as printed.
2. Which models are enabled, with the alias each one answers to.
3. Whether \`ANTHROPIC_BASE_URL\` is \`${options.routerUrl}\` in this session.

Never print an environment variable's value. Names only.
`;
  return { relativePath: 'commands/status.md', content };
}

function readmeFile(options: ClaudeCodeInstallOptions, settingsPath: string, launcherPath: string, pluginDir: string): InstallFile {
  const serveCommand = [
    posixQuote(options.cliPath),
    'serve',
    '--config',
    posixQuote(options.configPath),
    ...(options.claudeVersion !== undefined ? ['--claude-version', posixQuote(options.claudeVersion)] : ['--claude-version <your-claude-code-version>']),
  ].join(' ');

  const content = `# subagent-router integration for Claude Code

Generated by \`subagent-router install\`. Regenerate it instead of editing it.

Nothing here was written into your Claude Code configuration. Every file is opt-in and is used by
passing it to Claude Code on the command line.

## 1. Start the router

\`\`\`sh
${serveCommand}
\`\`\`

The router listens on \`${options.routerUrl}\`. It forwards to the gateway named by
\`ROUTER_GATEWAY_URL\`, so it works with any OpenAI-compatible gateway. No provider is named here.

## 2. Start Claude Code against it

\`\`\`sh
${posixQuote(launcherPath)}
\`\`\`

The launcher checks the router first, then runs \`claude --settings ${settingsPath}\`. Arguments are
passed through, so \`${posixQuote(launcherPath)} --continue\` works.

To do it by hand instead:

\`\`\`sh
claude --settings ${posixQuote(settingsPath)}
\`\`\`

\`--settings\` is a per-invocation setting. It does not edit \`~/.claude/settings.json\`.

## 3. Choose a model for a child

Put the marker on the first line of the Agent prompt:

\`\`\`
<subagent-router v="1" model="terra"/>
Implement the requested change.
\`\`\`

The parent keeps its own model.

## About the parent model

\`--parent-model\` writes \`ANTHROPIC_MODEL\` into \`settings.json\`. The gateway does receive it,
measured on Claude Code 2.1.270. The client also prints a warning for a model id its own catalog
does not know, and then assumes a 200k context window for it. Set
\`CLAUDE_CODE_MAX_CONTEXT_TOKENS\` if your model's window is larger.

Leave \`--parent-model\` out and the parent keeps whatever model Claude Code would use anyway. Your
gateway then has to accept that id.

## Optional: load the plugin

\`\`\`sh
claude --settings ${posixQuote(settingsPath)} --plugin-dir ${posixQuote(pluginDir)}
\`\`\`

The plugin adds two things and routes nothing by itself:

- a \`SessionStart\` hook that warns when the router is unreachable or when
  \`ANTHROPIC_BASE_URL\` does not point at it,
- a \`/subagent-router:status\` command that reports the config check and the catalog.

## About credentials

\`settings.json\` sets \`ANTHROPIC_AUTH_TOKEN\` to a placeholder that is not a credential. This is
deliberate. The router only replaces the request headers you name in \`ROUTER_GATEWAY_HEADERS\`, so
a client that is logged in to Anthropic would otherwise forward that real token to your gateway.

Put your gateway's own credential in \`ROUTER_GATEWAY_HEADERS\` in the shell that starts the router.
No file generated here holds a secret.
`;
  return { relativePath: 'README.md', content };
}

/**
 * Builds every file `install --client claude-code` writes. `outputDir` is only used to spell
 * absolute paths inside the generated scripts and docs; no path is read or written here.
 */
export function planClaudeCodeInstall(outputDir: string, options: ClaudeCodeInstallOptions): ClaudeCodeInstallPlan {
  const settingsPath = `${outputDir}/settings.json`;
  const launcherPath = `${outputDir}/claude-router`;

  return {
    routerUrl: options.routerUrl,
    files: [
      settingsFile(options),
      launcherFile(options, settingsPath),
      pluginManifest(options),
      hooksManifest(),
      healthCheckScript(options),
      statusCommand(options),
      readmeFile(options, settingsPath, launcherPath, outputDir),
    ],
  };
}
